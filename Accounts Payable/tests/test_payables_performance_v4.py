"""Benchmarks at scale: thousands of suppliers, invoices, payments, credits, operations.

Data is generated by ``tests/payables_support/bulkdata.py`` (direct, consistent inserts).
Results go to ``build/perf/<backend>-v4.json``; the assertions are loose ceilings.
``FMS_PERF_VENDORS`` (default 2000) and ``FMS_PERF_BILLS`` (default 5) set the size.
Run with ``-m perf``.
"""

import json
import os
import time
from datetime import date
from pathlib import Path

import pytest
from sqlalchemy import text

from app.modules.payables import services
from app.modules.payables.integration import Integrations
from app.modules.payables.schemas import PaymentRunCreateIn
from tests.payables_support import bulkdata

pytestmark = pytest.mark.perf

VENDORS = int(os.environ.get("FMS_PERF_VENDORS", "2000"))
BILLS = int(os.environ.get("FMS_PERF_BILLS", "5"))
RESULTS_DIR = Path(__file__).resolve().parents[1] / "build" / "perf"


def _timed(results, name, fn):
    started = time.perf_counter()
    value = fn()
    results[name] = round(time.perf_counter() - started, 3)
    return value


def test_benchmarks_at_scale(session, engine):
    results = {"backend": engine.dialect.name, "vendors": VENDORS, "bills_per_vendor": BILLS}
    world = _timed(results, "generate_seconds", lambda: bulkdata.generate(session, vendors=VENDORS, bills_per_vendor=BILLS))
    results.update(world["counts"])
    session.expire_all()
    as_of = date(2026, 4, 30)
    cash = world["accounts"]["cash"]
    vendor_id = world["vendor_ids"][0]

    run = _timed(results, "payment_run_proposal", lambda: services.create_run(
        session, PaymentRunCreateIn(actor="ops", pay_date=as_of, due_through=as_of, cash_account_id=cash), integrations=Integrations()))
    results["proposal_items"] = len(run.items)
    _timed(results, "payment_run_revalidation", lambda: services.revalidate_run(session, run))
    aging = _timed(results, "historical_aging", lambda: services.aging_report(session, as_of=date(2026, 1, 31)))
    _timed(results, "outstanding_report", lambda: services.outstanding_report(session, as_of=as_of))
    statement = _timed(results, "supplier_statement", lambda: services.vendor_statement(session, vendor_id, date_from=date(2025, 7, 1), date_to=as_of))
    _timed(results, "vendor_balances_all", lambda: services.vendor_balances(session, as_of=as_of))
    scan = _timed(results, "recovery_scan", lambda: services.recovery.scan(session, limit=500))
    results["incomplete_operations"] = len(scan)
    uid = session.execute(text("SELECT operation_uid FROM payment_operations WHERE state = 'completed' LIMIT 1")).scalar()
    _timed(results, "payment_status_lookup", lambda: services.diagnostics.operation_status(session, uid))
    _timed(results, "operation_listing_page", lambda: services.diagnostics.list_operations(session, page=3, page_size=50))
    csv = "kind,reference,date,amount\n" + "\n".join(
        f"invoice,{r[0]},{r[1]},{r[2]:.2f}" for r in session.execute(text(
            "SELECT invoice_number, invoice_date, total FROM supplier_bills WHERE vendor_id = :v"), {"v": vendor_id}).all())
    _timed(results, "supplier_statement_reconciliation", lambda: services.supplier_statements.preview(
        session, vendor_id, csv.encode(), file_name="bench.csv", statement_date=as_of))
    recon = _timed(results, "ap_to_gl_reconciliation", lambda: services.reconciliation_report(session, as_of=as_of))
    _timed(results, "period_end_validation", lambda: services.validate_period(session, date(2026, 3, 31)))
    replay = _timed(results, "historical_reconstruction_replay", lambda: services.reconstruction.replay(session, as_of))
    compare = _timed(results, "historical_reconstruction_compare", lambda: services.reconstruction.compare(session, as_of))

    assert recon.exceptions == [] and recon.total_difference == 0, recon.exceptions[:3]
    assert compare.findings == [], compare.findings[:3]
    assert statement.difference == 0
    assert aging.totals.total >= 0 and len(replay.bill_outstanding) > 0

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / f"{engine.dialect.name}-v4.json").write_text(json.dumps(results, indent=2, default=str))
    print("\nPERF", json.dumps(results, default=str))
    for key, value in results.items():
        if key.endswith(("_report", "_proposal", "_revalidation", "_aging", "_statement", "_scan", "_lookup", "_page",
                         "_reconciliation", "_validation", "_replay", "_compare", "_all")):
            assert value < 120, f"{key} took {value}s"
